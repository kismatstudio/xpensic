// Smoke test for the CSV id-based dedupe (punchlist #7).
// Verifies that:
//   • expensesToCSV writes the `id` column on every row.
//   • csvToExpenses preserves the id on each parsed record.
//   • Re-importing the same CSV into a store with matching ids is a no-op
//     for the existing rows (the main.js import handler is exercised via
//     a small simulation, since it lives in main.js and we can't run
//     browser-side DOM code in a node script).
//   • Store.addExpense accepts a caller-supplied id and preserves it.
//   • Store.addExpense still generates a fresh id when none is supplied.

import { expensesToCSV, csvToExpenses, CSV_COLUMNS } from "../js/csv.js";
import { Store, migrate, validate, normalizeExpense } from "../js/store.js";

let pass = 0;
let fail = 0;
function check(name, cond, extra) {
  if (cond) { console.log(`  PASS  ${name}`); pass++; }
  else { console.log(`  FAIL  ${name}` + (extra ? `  (${extra})` : "")); fail++; }
}

// Build a tiny state object the way Store.freshState would, but with
// some existing expenses. We avoid calling Store._write (no localStorage).
function freshState() {
  return {
    version: 2,
    settings: { currency: "INR", currencySymbol: "₹", currencyPosition: "before", dateFormat: "YYYY-MM-DD", theme: "system" },
    profile: { name: "Tester", phone: "9876543210", avatarDataUrl: "" },
    categories: [
      { id: "cat_food", name: "Food", color: "#ef4444", isDefault: true },
      { id: "cat_transport", name: "Transport", color: "#3b82f6", isDefault: true },
    ],
    budgets: { monthly: {} },
    expenses: [],
  };
}

const categories = [
  { id: "cat_food", name: "Food" },
  { id: "cat_transport", name: "Transport" },
];

console.log("\n[1] CSV round-trip preserves the id column");
{
  const expenses = [
    { id: "exp_a", amount: 100, date: "2026-07-01", time: "12:00", categoryId: "cat_food", paymentMethod: "cash", upiApp: "", note: "Lunch" },
    { id: "exp_b", amount: 50,  date: "2026-07-02", time: "09:30", categoryId: "cat_transport", paymentMethod: "upi", upiApp: "phonepe", note: "Cab" },
  ];
  const csv = expensesToCSV(expenses, categories);
  check("CSV header includes the id column", csv.split("\n")[0].split(",")[0] === "id");
  check("CSV_COLUMNS starts with id", CSV_COLUMNS[0] === "id");

  const result = csvToExpenses(csv, categories);
  check("parsed ok", result.ok === true && result.errors.length === 0, JSON.stringify(result.errors));
  check("first row preserves id 'exp_a'", result.expenses[0]?.id === "exp_a");
  check("second row preserves id 'exp_b'", result.expenses[1]?.id === "exp_b");
  check("second row preserves upiApp", result.expenses[1]?.upiApp === "phonepe");
}

console.log("\n[2] csvToExpenses leaves id undefined when the file has none (hand-edited CSV)");
{
  const csv = `date,time,amount,category,paymentMethod,upiApp,note\n2026-07-10,,200,Food,cash,,Dinner`;
  const result = csvToExpenses(csv, categories);
  check("parsed ok", result.ok === true && result.errors.length === 0, JSON.stringify(result.errors));
  check("row has no id (will be generated by the store)", result.expenses[0]?.id === undefined);
}

console.log("\n[3] Store.addExpense accepts a caller-supplied id and preserves it");
{
  const state = freshState();
  const exp = Store.addExpense(state, {
    id: "exp_caller_supplied",
    amount: 250,
    date: "2026-07-10",
    categoryId: "cat_food",
    note: "From CSV",
    paymentMethod: "cash",
  });
  check("returned expense has the caller id", exp.id === "exp_caller_supplied");
  check("expense pushed into the store with that id", state.expenses[0]?.id === "exp_caller_supplied");
}

console.log("\n[4] Store.addExpense still generates a fresh id when none is supplied");
{
  const state = freshState();
  const a = Store.addExpense(state, { amount: 10, date: "2026-07-10", categoryId: "cat_food" });
  const b = Store.addExpense(state, { amount: 20, date: "2026-07-10", categoryId: "cat_food" });
  check("first generated id is non-empty", typeof a.id === "string" && a.id.length > 0);
  check("second generated id is different from the first", a.id !== b.id);
  check("both ids have the exp_ prefix", a.id.startsWith("exp_") && b.id.startsWith("exp_"));
}

console.log("\n[5] Re-import simulation: dedupe by id, skip existing rows");
{
  // This mirrors what the main.js import handler now does.
  const state = freshState();
  // Seed the store with two existing expenses.
  Store.addExpense(state, { id: "exp_x", amount: 100, date: "2026-07-01", categoryId: "cat_food" });
  Store.addExpense(state, { id: "exp_y", amount: 200, date: "2026-07-02", categoryId: "cat_food" });
  const beforeIds = state.expenses.map((e) => e.id);

  // Build a CSV with the same two expenses plus a new one.
  const csv = expensesToCSV([
    { id: "exp_x", amount: 999, date: "2026-07-01", time: "", categoryId: "cat_food", paymentMethod: "cash", upiApp: "", note: "edited" }, // amount edited — should be skipped, not updated
    { id: "exp_y", amount: 200, date: "2026-07-02", time: "", categoryId: "cat_food", paymentMethod: "cash", upiApp: "", note: "unchanged" },
    { id: "exp_z", amount: 300, date: "2026-07-03", time: "", categoryId: "cat_food", paymentMethod: "cash", upiApp: "", note: "new" },
  ], categories);

  const result = csvToExpenses(csv, categories);
  check("CSV parsed cleanly", result.ok === true && result.errors.length === 0);

  // Dedupe pass — copy of the logic in main.js.
  const existingIds = new Set(state.expenses.map((e) => e.id));
  let added = 0, skipped = 0;
  for (const e of result.expenses) {
    if (e.id && existingIds.has(e.id)) { skipped++; continue; }
    Store.addExpense(state, e);
    if (e.id) existingIds.add(e.id);
    added++;
  }
  check("two existing rows were skipped", skipped === 2);
  check("one new row was added", added === 1);
  check("store now has exactly 3 expenses", state.expenses.length === 3);
  check("exp_x is unchanged (still 100, not the edited 999)", state.expenses.find((e) => e.id === "exp_x")?.amount === 100);
  check("exp_z is the new one", !!state.expenses.find((e) => e.id === "exp_z"));
  check("ids are preserved (no collisions)", new Set(state.expenses.map((e) => e.id)).size === state.expenses.length);
  // The original two ids should still be there unchanged.
  const afterIds = new Set(state.expenses.map((e) => e.id));
  for (const id of beforeIds) check(`original id "${id}" still present`, afterIds.has(id));
}

console.log("\n[6] Round-trip idempotency: export → import → export is a no-op");
{
  const state = freshState();
  Store.addExpense(state, { id: "exp_1", amount: 10, date: "2026-07-01", categoryId: "cat_food", paymentMethod: "cash" });
  Store.addExpense(state, { id: "exp_2", amount: 20, date: "2026-07-02", categoryId: "cat_food", paymentMethod: "upi", upiApp: "phonepe" });

  const csv1 = expensesToCSV(state.expenses, categories);
  const r1 = csvToExpenses(csv1, categories);
  const existingIds = new Set(state.expenses.map((e) => e.id));
  let added = 0, skipped = 0;
  for (const e of r1.expenses) {
    if (e.id && existingIds.has(e.id)) { skipped++; continue; }
    Store.addExpense(state, e);
    if (e.id) existingIds.add(e.id);
    added++;
  }
  check("first re-import added 0 new rows", added === 0);
  check("first re-import skipped 2 existing rows", skipped === 2);
  check("store still has 2 expenses", state.expenses.length === 2);

  // And doing it a third time is also a no-op.
  const csv2 = expensesToCSV(state.expenses, categories);
  const r2 = csvToExpenses(csv2, categories);
  const existingIds2 = new Set(state.expenses.map((e) => e.id));
  let added2 = 0;
  for (const e of r2.expenses) {
    if (e.id && existingIds2.has(e.id)) continue;
    Store.addExpense(state, e);
    added2++;
  }
  check("second re-import added 0 new rows", added2 === 0);
  check("store still has 2 expenses", state.expenses.length === 2);
}

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail === 0 ? 0 : 1);
